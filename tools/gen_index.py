#!/usr/bin/env python3
"""Generate SYMBOLS.md: every top-level function / const / let / var / class in src/*.js -> file:line.
All src files share ONE global scope (build.py concatenates them), so a name must be unique across files.
Run after edits:  python3 tools/gen_index.py   (also prints duplicate top-level names, if any)."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
SKIP = {"peerjs.min.js"}
DECL = re.compile(r"^(?:async\s+)?(function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)")


def build_order():
    s = open(os.path.join(ROOT, "build.py")).read()
    m = re.search(r"for f in \[(.*?)\]", s)
    return [x.strip().strip("'\"") for x in m.group(1).split(",")]


def symbols(path):
    out = []
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        m = DECL.match(line)  # Prettier keeps top-level declarations at column 0
        if m:
            out.append((m.group(2), m.group(1).replace("*", ""), n))
    return out


def main():
    order = build_order()
    files = order + sorted(f for f in os.listdir(SRC) if f.endswith(".js") and f not in order and f not in SKIP)
    rows, seen = [], {}
    for f in files:
        for name, kind, line in symbols(os.path.join(SRC, f)):
            rows.append((name, kind, f, line))
            seen.setdefault(name, []).append(f"{f}:{line}")
    dups = {k: v for k, v in seen.items() if len(v) > 1}
    L = ["# SYMBOLS", "", "Generated by `python3 tools/gen_index.py` — do not edit by hand; regenerate after changing src/.", "",
         f"{len(rows)} top-level declarations in {len(files)} files (build order).", ""]
    if dups:
        L += ["## Duplicate top-level names", "", "| name | locations |", "|---|---|"]
        L += [f"| `{k}` | {', '.join(v)} |" for k, v in sorted(dups.items())] + [""]
    cur = None
    for name, kind, f, line in rows:
        if f != cur:
            cur = f
            L += ["", f"## {f}", "", "| symbol | kind | line |", "|---|---|---|"]
        L.append(f"| `{name}` | {kind} | {line} |")
    open(os.path.join(ROOT, "SYMBOLS.md"), "w").write("\n".join(L) + "\n")
    print(f"SYMBOLS.md: {len(rows)} symbols, {len(dups)} duplicate names")
    for k, v in sorted(dups.items()):
        print("  dup", k, v)


if __name__ == "__main__":
    sys.exit(main())
